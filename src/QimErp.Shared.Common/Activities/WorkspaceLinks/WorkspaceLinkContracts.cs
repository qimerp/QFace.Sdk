using Temporalio.Activities;
using Temporalio.Workflows;

namespace QimErp.Shared.Common.Activities.WorkspaceLinks;

public static class WorkspaceLinkWorkflows
{
    public const string CommandWorkflowType = "WorkspaceLinkCommandWorkflow";
    public const string CommandTaskQueue = "qimerp-platform-workspace-link";
    public const string SyncWorkflowType = "WorkspaceLinkSyncWorkflow";
    public const string SyncTaskQueue = "qimerp-finance-workspace-link-sync";
    public const string SyncActivityName = "SyncWorkspaceLink:Accounting";
    public const string IntercompanyPurpose = "intercompany";

    public static string CommandWorkflowId(Guid linkId, WorkspaceLinkAction action) =>
        $"workspace-link-command-{linkId:N}-{action.ToString().ToLowerInvariant()}";

    public static string SyncWorkflowId(string tenantId, Guid linkId, long sourceVersion) =>
        $"workspace-link-sync-{tenantId}-{linkId:N}-{sourceVersion}";
}

public enum WorkspaceLinkAction
{
    Request,
    Accept,
    Decline,
    Revoke
}

public enum WorkspaceLinkDirection
{
    Outbound,
    Inbound
}

public enum WorkspaceLinkStatus
{
    Pending,
    Accepted,
    Declined,
    Revoked
}

/// <summary>
/// Accounting → Platform command for one workspace link. <see cref="TenantId"/> is the sending tenant from server context;
/// Platform acts only on links where that tenant is the requester or the resolved target.
/// </summary>
public class WorkspaceLinkCommand
{
    public string TenantId { get; set; } = string.Empty;

    /// <summary>Generated by the requesting Accounting tenant on <see cref="WorkspaceLinkAction.Request"/>.</summary>
    public Guid LinkId { get; set; }

    public WorkspaceLinkAction Action { get; set; }
    public string Purpose { get; set; } = WorkspaceLinkWorkflows.IntercompanyPurpose;

    /// <summary>Workspace domain of the partner; only read on <see cref="WorkspaceLinkAction.Request"/>.</summary>
    public string? TargetWorkspaceDomain { get; set; }

    public string ActorUserId { get; set; } = string.Empty;
}

/// <summary>
/// Platform → Accounting status of one link as seen by <see cref="TenantId"/>. The counterparty's tenant id is set only once
/// the link is accepted; before that an inbound row carries only the inviter's name and domain.
/// On Status=Revoked consumers update only status, version and responded-at; other fields may be defaults.
/// </summary>
public class WorkspaceLinkChanged
{
    public string TenantId { get; set; } = string.Empty;
    public Guid LinkId { get; set; }
    public string Purpose { get; set; } = WorkspaceLinkWorkflows.IntercompanyPurpose;
    public WorkspaceLinkDirection Direction { get; set; }
    public WorkspaceLinkStatus Status { get; set; }
    public string? CounterpartyTenantId { get; set; }
    public string? CounterpartyName { get; set; }
    public string CounterpartyDomain { get; set; } = string.Empty;
    public DateTime RequestedAtUtc { get; set; }
    public DateTime? RespondedAtUtc { get; set; }
    public DateTime ExpiresAtUtc { get; set; }
    public long SourceVersion { get; set; }
}

/// <summary>Hosted by Platform on <see cref="WorkspaceLinkWorkflows.CommandTaskQueue"/>.</summary>
[Workflow(WorkspaceLinkWorkflows.CommandWorkflowType)]
public interface IWorkspaceLinkCommandWorkflow
{
    [WorkflowRun]
    Task RunAsync(WorkspaceLinkCommand command);
}

/// <summary>Started by Platform on <see cref="WorkspaceLinkWorkflows.SyncTaskQueue"/>, once per tenant that must see the change.</summary>
[Workflow(WorkspaceLinkWorkflows.SyncWorkflowType)]
public interface IWorkspaceLinkSyncWorkflow
{
    [WorkflowRun]
    Task RunAsync(WorkspaceLinkChanged change);
}

/// <summary>Hosted by Accounting on <see cref="WorkspaceLinkWorkflows.SyncTaskQueue"/>.</summary>
public interface IWorkspaceLinkSyncActivity
{
    [Activity(WorkspaceLinkWorkflows.SyncActivityName)]
    Task SyncAsync(WorkspaceLinkChanged change);
}
